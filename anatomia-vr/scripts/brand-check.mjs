import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createHash} from 'node:crypto';
const root=new URL('../',import.meta.url);
const read=p=>fs.readFileSync(new URL(p,root),'utf8');
const logo=fs.readFileSync(new URL('assets/medsi-college-logo.png',root));
assert.equal(createHash('sha256').update(logo).digest('hex'),'ec458823f107bdc13fe0fd01fb11b592d2a3a73d27e5b2c50b5b448a44484075','Preserve the user-supplied College MEDSI logo byte-for-byte');
const html=read('index.html'),css=read('medsi.css'),offline=read('ANATOMIA-lesson-offline.html');
assert.ok(html.includes('Совместный проект с колледжем МЕДСИ'));
assert.ok(offline.includes('Совместный проект с колледжем МЕДСИ'));
assert.ok(html.indexOf('medsi.css')>html.indexOf('teaching.css'));
assert.match(html,/width="2048" height="504" alt="Колледж МЕДСИ"/);
assert.ok(!/@import|fonts\.googleapis/.test(read('style.css')+css));
assert.ok(offline.includes('data:image/png;base64,'+logo.toString('base64')));
assert.ok(offline.includes(css),'Offline lesson includes the current brand stylesheet');
assert.ok(!/src="\.\/assets\/medsi-college-logo\.png"/.test(offline));
const luminance=hex=>{const c=hex.match(/\w\w/g).map(x=>parseInt(x,16)/255).map(x=>x<=.04045?x/12.92:((x+.055)/1.055)**2.4);return c[0]*.2126+c[1]*.7152+c[2]*.0722;};
const contrast=(a,b)=>{let x=luminance(a),y=luminance(b);return (Math.max(x,y)+.05)/(Math.min(x,y)+.05);};
for(const [fg,bg] of [['16324f','ffffff'],['496375','f4f9fb'],['ffffff','087f83'],['04558a','dceef3'],['ffffff','066a70']])assert.ok(contrast(fg,bg)>=4.5,`${fg}/${bg} must pass normal text contrast`);
console.log(JSON.stringify({status:'passed',logo:'original SHA-256 verified',offline:'embedded logo and current CSS',brandTextPairs:5,scope:'Static brand invariants, not a full browser accessibility audit'}));
